/**
 * Закріплення записів угорі списку (SPEC §7 List Report; ADR-0024). Як у project-a: особисте — у кожного
 * користувача свій набір, чуже закріплення ніхто не бачить і не змінює.
 *
 * Контракт (під `/api/v1`, конвенції ADR-0002):
 * - `PUT /<ресурс>/:id/pin` → 204 — закріпити; `DELETE /<ресурс>/:id/pin` → 204 — відкріпити. Обидва
 *   ідемпотентні: повтор після загубленої відповіді нічого не змінює. Право — те саме, що на читання
 *   списку (`<ресурс>:read`): запис не змінюється, змінюється лише порядок у списку цього користувача.
 * - Список (`GET /<ресурс>`) і запис (`GET /<ресурс>/:id`) віддають `pinned: true` для закріплених
 *   читачем; немає поля — не закріплено.
 * - Закріплені, що проходять фільтри й вкладку, стоять першим блоком на початку списку — на першій
 *   сторінці й у першому вікні прокрутки — у порядку закріплення (старші вище: новий стає під
 *   ними, тож наявні не рухаються), далі решта за `sort`. `total` і лічильники вкладок закріплення
 *   не змінює: воно переставляє рядки, а не додає й не ховає.
 * - Межа — `PIN_LIMIT` на ресурс для користувача: понад неї `PUT` → 422 `{ code: "pin_limit" }`.
 *   Закріплений блок сервер бере цілим на кожен запит списку, тож межа тримає запит малим.
 * - Видалений чи архівований запис сервер відкріплює в усіх.
 */

/** Сегмент шляху закріплення: `/<ресурс>/:id/pin`. */
export const PIN_PATH = "pin"
/** Скільки записів одного ресурсу користувач може закріпити (як у project-a). */
export const PIN_LIMIT = 50
/** Код помилки, коли межу вичерпано (422). */
export const PIN_LIMIT_CODE = "pin_limit"

/** Запис, який сервер позначає закріпленим для читача. */
export interface PinnableRecord {
  pinned?: boolean
}

/** Закріплений читачем (`pinned: true`); без поля — ні. */
export const isPinned = (record: object): boolean =>
  (record as PinnableRecord).pinned === true

/**
 * Порядок списку із закріпленими: спершу закріплені в порядку `pins` (порядок закріплення), далі
 * решта в отриманому порядку. Без закріплених — той самий масив (без копії 10 000 записів). Для
 * моків і серверів на TypeScript.
 */
export function pinnedFirst<T extends { id: string }>(
  records: readonly T[],
  pins: readonly string[],
): readonly T[] {
  if (pins.length === 0) return records
  const rank = new Map(pins.map((id, index) => [id, index]))
  const pinned = records
    .filter((record) => rank.has(record.id))
    .sort((a, b) => (rank.get(a.id) ?? 0) - (rank.get(b.id) ?? 0))
  return [...pinned, ...records.filter((record) => !rank.has(record.id))]
}
